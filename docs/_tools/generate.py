"""Generated documentation pages: nothing here is written by hand.

Two families, both regenerated on every build (``builder-inited``):

1. **Wrapper pages.** ``README.md``, ``SPEC.md`` and ``LICENSING.md`` are the
   documentation and remain its source. Not a line of them is copied here: each
   page is an ``include`` directive whose start and end lines are computed *from
   the headings of the file itself*. If a section is renamed or moved, the
   wrapper follows it on the next build; if it disappears, the build stops and
   says so. The Italian site translates the included text through gettext
   (``docs/locale/it``), so the wrappers are the same in both languages.

2. **Catalogues.** Definitions, vocabularies, snapshot status: every figure
   comes from the package (the same computations as ``stratigraph-templates
   info`` and ``vocab``) or from ``registry/s3dgraphy-snapshot.json``, never
   from a typed table. Their few sentences are written here in both languages
   (``TEXT``), because they are generated, not included.

Run by hand: ``python docs/_tools/generate.py [en|it]``.
"""

